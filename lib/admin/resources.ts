export function allowed(role: string, area: string) {
  if (area === "notifications")
    return [
      "SUPER_ADMIN",
      "ADMIN",
      "MANAGER",
      "ORDER_MANAGER",
      "PRODUCT_MANAGER",
      "CONTENT_EDITOR",
      "CUSTOMER_SUPPORT",
      "MARKETING",
      "REPORT_VIEWER",
    ].includes(role);
  return (
    role === "SUPER_ADMIN" ||
    (role === "ADMIN" && area !== "users") ||
    (role === "MANAGER" && !["users", "settings"].includes(area)) ||
    (
      {
        PRODUCT_MANAGER: ["products", "inventory", "media"],
        ORDER_MANAGER: ["orders", "customers"],
        CONTENT_EDITOR: ["content", "media"],
        CUSTOMER_SUPPORT: ["customers", "reviews"],
        MARKETING: ["marketing", "reviews", "rewards"],
        REPORT_VIEWER: ["reports"],
      } as Record<string, string[]>
    )[role]?.includes(area) ||
    false
  );
}
