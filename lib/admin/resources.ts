import { z } from "zod";
const text = z.string().max(5000);
const short = z.string().trim().min(1).max(200);
const money = z.preprocess(
  (v) => (v === "" ? undefined : v),
  z.coerce.number().min(0).max(100000000),
);
const integer = z.coerce.number().int();
const link = z
  .string()
  .max(2000)
  .refine(
    (v) => !v || /^\/(?!\/)/.test(v) || /^https:\/\//.test(v),
    "Use a local path or HTTPS URL",
  );
const opt = (v: z.ZodType) => v.nullable().optional();
export type Field = {
  label: string;
  type?:
    | "text"
    | "textarea"
    | "number"
    | "checkbox"
    | "select"
    | "json"
    | "datetime-local";
  options?: string[];
  required?: boolean;
};
export type Resource = {
  title: string;
  table: string;
  area: string;
  columns: string[];
  search: string;
  fields: Record<string, Field>;
  schema: z.ZodObject;
  readonly?: boolean;
  archive?: string;
};
function define(
  title: string,
  table: string,
  area: string,
  columns: string[],
  search: string,
  fields: Record<string, Field>,
  shape: Record<string, z.ZodType>,
  extras: Partial<Resource> = {},
): Resource {
  return {
    title,
    table,
    area,
    columns,
    search,
    fields,
    schema: z.object(shape).strict(),
    ...extras,
  };
}
